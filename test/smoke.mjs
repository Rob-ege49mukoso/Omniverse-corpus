
import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';

const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://localhost:5173', { waitUntil: 'networkidle' });
await page.getByRole('heading', { name: 'Vue d’ensemble', exact: true }).waitFor();
console.log('DASHBOARD', await page.evaluate(() => ({ title: document.title, width: innerWidth, scrollWidth: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight, panels: [...document.querySelectorAll('.hero-banner,.metrics-grid,.dashboard-two-column,.dashboard-footer')].map(element => ({ class: element.className, y: Math.round(element.getBoundingClientRect().y), height: Math.round(element.getBoundingClientRect().height), width: Math.round(element.getBoundingClientRect().width) })) })));
await page.screenshot({ path: '/tmp/nexus-desktop.png', fullPage: true });
await page.getByRole('button', { name: 'Nouveau corpus', exact: true }).click();
await page.getByRole('dialog').waitFor();
await page.locator('#multiplier').fill('2');
await page.locator('.input-with-suffix input').fill('test_corpus.nxs');
await page.getByRole('button', { name: 'Compiler le corpus', exact: true }).click();
await page.getByRole('heading', { name: 'test_corpus.nxs', exact: true }).waitFor();
console.log('COMPILE', await page.getByRole('dialog').innerText());
const downloadPromise = page.waitForEvent('download');
await page.getByRole('button', { name: 'Télécharger .nxs', exact: true }).click();
const download = await downloadPromise;
await download.saveAs('/tmp/nexus-test.nxs');
await page.getByRole('button', { name: 'Octets & hexadécimal' }).click();
await expect(page.locator('.hex-row').first()).toBeVisible();
await page.getByRole('textbox', { name: 'Octet à mettre en évidence' }).fill('FF');
await expect(page.locator('.hex-highlight').first()).toBeVisible();
await page.getByRole('button', { name: 'Séquences', exact: true }).click();
await page.locator('.sequence-list button').first().click();
await page.getByRole('button', { name: 'Fermer', exact: true }).click();
await page.reload({ waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Corpus de données', exact: false }).first().click();
await page.getByRole('textbox', { name: 'Rechercher un corpus' }).fill('test_corpus');
await expect(page.locator('.corpus-name')).toHaveCount(1);
console.log('PERSISTENCE OK');
await page.locator('.corpus-name').click();
await page.getByRole('button', { name: 'Configurer le run' }).click();
await page.getByRole('heading', { name: 'Entraînement', exact: true }).waitFor();
await page.getByRole('button', { name: 'Lancer la simulation' }).click();
await page.waitForTimeout(1300);
await page.getByRole('button', { name: 'Mettre en pause' }).click();
assert((await page.locator('.run-status').innerText()) === 'Paused');
await page.getByRole('button', { name: 'Reprendre' }).click();
await page.getByRole('button', { name: 'Exporter le moteur', exact: false }).first().click();
const scriptDownload = page.waitForEvent('download');
await page.getByRole('button', { name: 'Télécharger le moteur' }).click();
await (await scriptDownload).saveAs('/tmp/nexus-train.py');
await page.getByRole('button', { name: 'Fermer', exact: true }).click();
console.log('TRAINING & EXPORT OK');
for (const hash of ['models', 'protocols', 'docs', 'settings', 'pipeline', 'overview']) {
  await page.goto('http://localhost:5173/#' + hash, { waitUntil: 'networkidle' });
  assert(await page.locator('main h1').count() === 1);
  console.log('PAGE', hash, await page.locator('main h1').innerText());
}
await page.keyboard.press('Control+k');
await page.getByRole('textbox', { name: 'Recherche globale' }).fill('protocoles');
await page.locator('.command-results button').first().click();
await page.getByRole('button', { name: 'Hexadécimal', exact: true }).click();
await expect(page.locator('.hex-row').first()).toBeVisible();
await page.getByRole('button', { name: /VISION.*FF 05/ }).click();
await page.getByRole('button', { name: 'Séquence', exact: true }).click();
await page.getByRole('button', { name: 'Lecture', exact: true }).click();
await page.waitForTimeout(500);
assert((await page.locator('.video-controls').innerText()).includes('Pause'));
console.log('SEARCH & VIDEO OK');
await page.setViewportSize({ width: 390, height: 844 });
await page.goto('http://localhost:5173/#overview', { waitUntil: 'networkidle' });
assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
await page.screenshot({ path: '/tmp/nexus-mobile.png', fullPage: true });
await page.getByRole('button', { name: 'Ouvrir le menu' }).click();
await page.getByRole('button', { name: 'Corpus de données', exact: false }).first().click();
assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
console.log('MOBILE OK', await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight })));
console.log('BROWSER ERRORS', errors);
assert.deepEqual(errors, []);
await browser.close();

process.on("uncaughtException", error => { console.error("TEST FAILED:", error.message); process.exit(1); });
process.on("unhandledRejection", error => { console.error("TEST FAILED:", error instanceof Error ? error.message : error); process.exit(1); });
