import type { TrainingConfig } from "./nxs";

export interface PythonExecutionResult {
  success: boolean;
  output: string;
  error?: string;
}

/** Generate a PyTorch architecture scaffold; this does not train without a dataset. */
export function getPythonScript(config: TrainingConfig): string {
  const heads = Math.max(1, Math.floor(Number(config.heads) || 1));
  let dModel = Math.max(heads, Math.floor(Number(config.dModel) || heads));
  if (dModel % heads !== 0) dModel += heads - (dModel % heads);
  const settings = {
    model: config.model,
    d_model: dModel,
    heads,
    layers: Math.max(1, Math.floor(Number(config.layers) || 1)),
    batch_size: Math.max(1, Math.floor(Number(config.batchSize) || 1)),
    learning_rate: Number(config.learningRate) || 0.0003,
    epochs: Math.max(1, Math.floor(Number(config.epochs) || 1)),
    block_size: Math.max(1, Math.floor(Number(config.block) || 256)),
    vocab_size: 256,
  };
  return [
    '"""OmniCore architecture scaffold generated by NEXUS-ZERO.',
    'This file defines a model only; it does not train without a dataset.',
    'Install PyTorch first: https://pytorch.org/get-started/locally/',
    '"""',
    "import torch",
    "from torch import nn",
    "",
    "CONFIG = " + JSON.stringify(settings, null, 2),
    "",
    "class OmniCoreModel(nn.Module):",
    "    def __init__(self):",
    "        super().__init__()",
    '        self.token_embedding = nn.Embedding(CONFIG["vocab_size"], CONFIG["d_model"])',
    '        self.position_embedding = nn.Embedding(CONFIG["block_size"], CONFIG["d_model"])',
    "        layer = nn.TransformerEncoderLayer(",
    '            d_model=CONFIG["d_model"],',
    '            nhead=CONFIG["heads"],',
    '            dim_feedforward=CONFIG["d_model"] * 4,',
    "            batch_first=True,",
    "        )",
    '        self.encoder = nn.TransformerEncoder(layer, num_layers=CONFIG["layers"])',
    '        self.output = nn.Linear(CONFIG["d_model"], CONFIG["vocab_size"])',
    "",
    "    def forward(self, input_ids):",
    "        if input_ids.ndim != 2:",
    '            raise ValueError("input_ids must have shape [batch, sequence]")',
    "        length = input_ids.shape[1]",
    '        if length > CONFIG["block_size"]:',
    '            raise ValueError("sequence exceeds configured block_size")',
    "        positions = torch.arange(length, device=input_ids.device).unsqueeze(0)",
    "        hidden = self.token_embedding(input_ids) + self.position_embedding(positions)",
    "        causal_mask = torch.triu(torch.ones(length, length, device=input_ids.device, dtype=torch.bool), diagonal=1)",
    "        hidden = self.encoder(hidden, mask=causal_mask)",
    "        return self.output(hidden)",
    "",
    "def main():",
    "    model = OmniCoreModel()",
    '    sample = torch.randint(0, CONFIG["vocab_size"], (1, min(8, CONFIG["block_size"])))',
    "    logits = model(sample)",
    '    print("Model:", CONFIG["model"])',
    '    print("Output shape:", tuple(logits.shape))',
    '    print("Architecture check complete. No training data was supplied.")',
    "",
    'if __name__ == "__main__":',
    "    main()",
    "",
  ].join("\n");
}

export async function executePython(code: string): Promise<PythonExecutionResult> {
  try {
    const response = await fetch("https://emkc.org/api/v2/piston/execute", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ language: "python", version: "3.10.0", files: [{ name: "main.py", content: code }] }),
    });
    if (!response.ok) throw new Error("Python API error: " + response.status);
    const result = await response.json();
    const run = result?.run;
    if (!run) throw new Error("Python execution service returned an invalid response.");
    return { success: run.code === 0, output: run.output || "", error: run.stderr || undefined };
  } catch (error) {
    return { success: false, output: "", error: error instanceof Error ? error.message : "Unknown error" };
  }
}
